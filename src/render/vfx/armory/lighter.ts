import * as THREE from 'three';
import { abOff, onAbChange } from '../../look/abSwitch';

/**
 * The Armory's heaviest work made lighter for the game's camera (the G moves' frame drops).
 *
 * The Armory frames its effects from eleven metres back; the game's camera rides a few metres behind the fighter, so an
 * area move's smoke, dust and ground marks cover several times the screen they were budgeted for, and at 2x the
 * pixels. Measured on every fighter's G (frames held at each move's worst moments and redrawn with each piece
 * hidden), the frame time went, over and over, to the Armory's shared kits:
 *  - **particles drawn as smoke** (ParticleSystem's SMOKE shape: three octaves of 3D simplex noise for every pixel of
 *    every puff): Magatsu's pyre smoke, Shakudo's dust, Murex's beam smoke, Dorado's dust wall, KoKo's, Ippon's;
 *  - **ground fields and decals** whose noise is paid for over every pixel, where nothing can show as much as where it
 *    can: Senko's char, Shakudo's and Ippon's cracks and dust rings, Magatsu's scorches;
 *  - **raymarched volumes** covering most of the screen: Tancho's steam, Hinomoto's pall, Bellows' fire.
 * The vendored files stay as the Armory ships them (vendor/, regenerated by its script): this patches the programs the
 * host adapts (host.ts adaptNode), as the lens fade does, and the casts of the dustiest effects (effect.ts).
 *
 * What changes, and what does not:
 *  - Particles (exact): the alpha a particle has over its life is known before its shape; a fragment that no shape
 *    could lift over the discard threshold (fade x opacity under 1/250) is dropped before the noise is paid for. The
 *    shape's mask is at most 1 and the soft fade at most 1, so the very same fragments are discarded as before.
 *  - Particles (faint and mid-opacity smoke): a puff's octaves follow how much it can show (PUFF) - one under a tenth of
 *    its opacity, two from there, three from half - eased between so no edge changes from one frame to the next.
 *  - Particles (smoke, exact): the noise is bounded, so once a fragment's octaves so far put it further out than the
 *    rest could bring it back, it is discarded there, as it would have been after them (a fifth of every puff's quad,
 *    a tenth of its noise).
 *  - Ground fields (exact): the mark loops stop at the marks there are.
 *  - Ground decals (exact): a crack beyond its spreading reach, a dust ring beyond its radius and a scorch whose noise
 *    still to come could not lift it over the discard are dropped before that noise.
 *  - Volumes, on a hull covering more than a quarter of the screen (the frame held and drawn both ways, pixel by pixel):
 *    - every VolumeHull medium but flame (steam, smoke, sand, mist, spores, the void) keeps its steps - fewer moved
 *      Tancho's steam edge and Tsubute's pollen edge, which the film look's ink pass then drew as dark squiggles - and
 *      one built with a self-shadow takes it from one tap midway along the two it stood for, at one octave: a soft term
 *      under a lit side that is past white in the game's light (Tancho's steam: not one pixel changed, its volume 40%
 *      cheaper);
 *    - a glowing one (VolumeHull's flame, the volumetric fires, the found pack's fire sim) marches half its steps,
 *      never under 12: each step is weighted by its length, so the density holds (Hinomoto's pall, Bellows' fire: no
 *      pixel moved more than 42 of 255, under a hundred moved more than 16).
 *  - The dustiest casts (LIGHTER_SETS): a third fewer puffs, a little more opaque each, or smaller ones.
 * What the ten heaviest G moves add to a frame at their worst held moment, before -> after (1920x1080 at 2x, High, an
 * M4 Mac mini; two throws of the same dice): Magatsu 148 -> 88 ms, Tancho 94 -> 43, Murex 81 -> 37, Shakudo 69 -> 26,
 * Dorado 66 -> 36, Rakucho 46 -> 21, Amagoi 36 -> 15, Ippon 34 -> 19, Buna 34 -> 15; Tsubute's 42 not (its pollen is a
 * medium that keeps its steps).
 * `?ab=lightfx` turns all of it off (the probe flips it in a running page: the same frame drawn both ways).
 */
export const LIGHT = { value: abOff('lightfx') ? 0 : 1 };
onAbChange(() => { LIGHT.value = abOff('lightfx') ? 0 : 1; });

const DECL = 'uniform float armoryLight;\n';
/** Where a smoke puff takes its second and third octaves, by the alpha it can reach (fade x opacity): the second eased
 *  in over x..y, the third over z..w. The third octave moves a puff's mask by 0.016 on average (0.1 at most) and is
 *  paid for over every pixel of every puff: a mid-opacity dust (KoKo's, Ippon's, Minase's at a third, Dorado's wall at
 *  0.55) takes it only from half its reach (held frames, the octave there against not: no pixel moved more than 9 of
 *  255; Dorado's wall 10 ms cheaper). */
export const PUFF = new THREE.Vector4(.07, .12, .5, .65);
const PUFF_U = { value: PUFF };
/** The smoke shape's exact early discard (1 on, 0 off; see lighterShader): kept switchable for measuring. */
export const PUFF_CUT = { value: 1 };
/** The ground decals' exact early discards (1 on, 0 off; see lighterShader), switchable as PUFF_CUT. */
export const DECAL_CUT = { value: 1 };

/** The ground decal kit's fragment, as the Armory writes it (effects/GroundDecals.js DECAL_FRAGMENT): CRACK's branches and
 *  reach, DUSTRING's noise. */
const DECAL_CRACK = `      float ang = atan(c.y, c.x);
      float branch = ridged(vec3(cos(ang), sin(ang), uSeed * 5.0) * 2.6, 4);
      float spread = smoothstep(0.0, 0.45, uAge);
      float radial = smoothstep(spread, spread * 0.35, d);`;
const DECAL_DUST = `      float radius = mix(0.1, 1.0, pow(uAge, 0.4));
      float n = fbm3(vec3(c * 3.1, uSeed * 7.0 + uTime * 0.2));`;
const DECAL_SCORCH = `      float n = fbm3(vec3(c * 2.4, uSeed * 13.0));
      float burn = smoothstep(1.0, 0.15, d + n * 0.45);`;

/** The particle kit's fragment, as the Armory writes it (ParticleSystem.js PARTICLE_FRAGMENT). */
const PARTICLE_MASK = /float mask = shapeMask\(vUv\);\s*if \(mask <= 0\.004\) discard;\s*\/\/ Alpha over lifetime\.\s*float fade = (smoothstep\(0\.0, max\(uFadeIn, 1e-3\), vT\) \*\s*\(1\.0 - smoothstep\(clamp\(uFadeOut, 0\.0, 0\.999\), 1\.0, vT\)\));/;
const SMOKE_NOISE = 'float n = fbm3(vec3(c * 1.6, vSeed * 21.0 + vClock * 0.25));';
const SHAPE_FN = 'float shapeMask(vec2 uv) {';
/** The ground field's per-slot gate (GroundField.js: POCK's height, cover and heat, RUT's force). */
const MARK_GATE = /float on = step\(float\(i\), uMarkCount - 1\.0\);/g;

/** A program of an Armory kit made lighter (see above), where it is one of the kits; any other is left as it is. */
export function lighterShader(shader: { uniforms: Record<string, unknown>; fragmentShader: string }) {
  let src = shader.fragmentShader, touched = false;
  if (PARTICLE_MASK.test(src) && src.includes(SHAPE_FN)) {
    src = src.replace(PARTICLE_MASK, (_m, fade) => `// Alpha over lifetime (first: no shape lifts a fragment whose life has not the alpha to clear the threshold).
    float fade = ${fade};
    if (armoryLight > 0.5 && fade * uOpacity < 0.004) discard;
    armoryReach = armoryLight > 0.5 ? fade * uOpacity : 1.0;
    float mask = shapeMask(vUv);
    if (mask <= 0.004) discard;`);
    src = src.replace(SHAPE_FN, `uniform vec4 armoryPuff;\nuniform float armoryPuffCut;\nfloat armoryReach = 1.0;\n${SHAPE_FN}`);
    shader.uniforms.armoryPuff = PUFF_U;
    shader.uniforms.armoryPuffCut = PUFF_CUT;
    // A faint puff's erosion: the octaves it can show (three from a quarter's opacity, two from a tenth), eased.
    if (src.includes(SMOKE_NOISE)) src = src.replace(SMOKE_NOISE, `vec3 armoryP = vec3(c * 1.6, vSeed * 21.0 + vClock * 0.25);
      float armoryW2 = smoothstep(armoryPuff.x, armoryPuff.y, armoryReach), armoryW3 = smoothstep(armoryPuff.z, armoryPuff.w, armoryReach);
      vec3 armoryP2 = armoryP * 2.02, armoryP3 = armoryP2 * 2.02;
      float n = 0.5 * snoise(armoryP);
      // (Exact: this noise never passes 1.1 either way (1.04 at its most, sampled), so the octaves still to come move
      // d + n * 0.42 by at most 0.462 times their weights; a fragment they could not bring back under the discard
      // line (0.9633: a mask of 0.004) is discarded now, as it would be once they were paid for.)
      bool armoryCut = armoryLight > 0.5 && armoryPuffCut > 0.5;
      if (armoryCut && d + n * 0.42 - (armoryW2 * 0.25 + armoryW3 * 0.125) * 0.462 > 0.966) return 0.0;
      if (armoryW2 > 0.0) n += armoryW2 * 0.25 * snoise(armoryP2);
      if (armoryCut && d + n * 0.42 - armoryW3 * 0.125 * 0.462 > 0.966) return 0.0;
      if (armoryW3 > 0.0) n += armoryW3 * 0.125 * snoise(armoryP3);`);
    touched = true;
  }
  if (MARK_GATE.test(src)) {
    MARK_GATE.lastIndex = 0;
    src = src.replace(MARK_GATE, 'if (armoryLight > 0.5 && float(i) >= uMarkCount) break;\n      float on = step(float(i), uMarkCount - 1.0);');
    touched = true;
  }
  MARK_GATE.lastIndex = 0;
  // The ground decals (exact): a crack is never more than its reach from the centre as it spreads, and a dust ring's
  // noise lifts it to 0.6 + 0.5 x 0.96 at most (under 1.15); a fragment that cannot clear the kit's own discard (alpha
  // 0.004) at that most is dropped before its noise (CRACK: four octaves of ridged noise, DUSTRING: three of simplex).
  if (src.includes(DECAL_CRACK) || src.includes(DECAL_DUST) || src.includes(DECAL_SCORCH)) {
    // (SCORCH: its fbm3 taken octave by octave, as fbm3 takes them; a burn the octaves still to come could not lift over
    // the discard - each moves d + n * 0.45 by at most its weight x 1.1 x 0.45 - is dropped before them and the embers.)
    src = src.replace(DECAL_SCORCH, `      float armoryK = 0.85 * fadeOut * uIntensity;
      bool armoryCut = armoryLight > 0.5 && armoryDecalCut > 0.5;
      if (armoryCut && armoryK < 0.004) discard;
      vec3 armoryQ = vec3(c * 2.4, uSeed * 13.0);
      float n = 0.5 * snoise(armoryQ);
      if (armoryCut && smoothstep(1.0, 0.15, d + n * 0.45 - 0.375 * 0.495) * armoryK < 0.004) discard;
      n += 0.25 * snoise(armoryQ * 2.02);
      if (armoryCut && smoothstep(1.0, 0.15, d + n * 0.45 - 0.125 * 0.495) * armoryK < 0.004) discard;
      n += 0.125 * snoise(armoryQ * 2.02 * 2.02);
      float burn = smoothstep(1.0, 0.15, d + n * 0.45);`);
    src = src.replace(DECAL_CRACK, `      float spread = smoothstep(0.0, 0.45, uAge);
      float radial = smoothstep(spread, spread * 0.35, d);
      if (armoryLight > 0.5 && armoryDecalCut > 0.5 && radial * 0.95 * fadeOut * uIntensity < 0.004) discard;
      float ang = atan(c.y, c.x);
      float branch = ridged(vec3(cos(ang), sin(ang), uSeed * 5.0) * 2.6, 4);`)
      .replace(DECAL_DUST, `      float radius = mix(0.1, 1.0, pow(uAge, 0.4));
      if (armoryLight > 0.5 && armoryDecalCut > 0.5 && smoothstep(radius, radius * 0.35, d) * 1.15 * (1.0 - uAge) * 0.7 * uIntensity < 0.004) discard;
      float n = fbm3(vec3(c * 3.1, uSeed * 7.0 + uTime * 0.2));`);
    src = `uniform float armoryDecalCut;\n${src}`;
    shader.uniforms.armoryDecalCut = DECAL_CUT;
    touched = true;
  }
  const hull = lighterHull(src, shader.uniforms);
  if (hull) { src = hull; touched = true; }
  if (!touched) return;
  shader.uniforms.armoryLight = LIGHT;
  shader.fragmentShader = DECL + src;
}

/** Effects too heavy for the game's close camera whatever their programs do - their dust overdraws, puff over puff -
 *  cast lighter with the switch on (effect.ts): each key times its number, on what the cast has (the fit's, the kit's). */
export const LIGHTER_SETS: Readonly<Record<string, Readonly<Record<string, number>>>> = {
  // The dustiest G moves: their dust rolls through the game's camera, a hundred big puffs deep. Each cast with about a
  // third fewer puffs, each a little more opaque, or (Shakudo's, already dense) the puffs 15% smaller.
  ext_bend_earth: { dustSize: .85 },
  blade_quake: { dustRing: .65, dustOpacity: 1.15 },
  will_sovereign: { dustWall: .65, dustOpacity: 1.15 },
  stonespine: { dustRate: .65, burstDust: .65, dustOpacity: 1.15 },
  // (Not Banjaku's volley smoke: its cloud tapers to nothing, and a third fewer puffs made it clear a beat early.)
};

/** A cast's values with its effect's lighter set applied, with the switch on (effect.ts, as the cast is set up): each key
 *  times its number, on the value the cast has so far (else the vendored one). Never rounded: a size of 1 is a size, and
 *  the abilities round their own counts and rates (Math.round, a RateEmitter's tick). */
export function lighterCast(effectId: string, values: Map<string, unknown>, defaults: Readonly<Record<string, unknown>>, sets = LIGHTER_SETS) {
  if (LIGHT.value <= .5) return;
  for (const [key, by] of Object.entries(sets[effectId] ?? {})) {
    const v = values.get(key) ?? defaults[key];
    if (typeof v === 'number') values.set(key, v * by);
  }
}

/** VolumeHull's fragment, as the Armory writes it (vfx/VolumeHull.js): its fbm's octave loop, its self-shadow's density
 *  and where a self-shadow tap stands. */
const HULL_FBM = 'float volFbm(vec3 p) {';
const HULL_OCTAVE = 'if (float(i) >= uOctaves) break;';
const HULL_SHADOW = /float shadowDensity\(vec3 lp, vec3 wp\) \{\s*float shape, detail, event;\s*return mediumDensity\(lp, wp, shape, detail, event\);\s*\}/;
const HULL_TAP = 'float h = uShadowLength * (0.45 + float(s) * 1.1);';

/** A VolumeHull's program made able to take its self-shadow lighter (each hull's own uniforms, set before each draw by
 *  `lighterVolume`): `armoryShadowCut` octaves fewer for the shadow taps' density, and `armoryTapShift` metres-in-lengths
 *  further along the light for a lone tap (midway between the two it stands in for). */
function lighterHull(src: string, uniforms: Record<string, unknown>): string | null {
  if (!src.includes(HULL_FBM) || !src.includes(HULL_OCTAVE) || !HULL_SHADOW.test(src) || !src.includes(HULL_TAP)) return null;
  uniforms.armoryShadowCut ??= { value: 0 };
  uniforms.armoryTapShift ??= { value: 0 };
  return src
    .replace(HULL_FBM, `uniform float armoryShadowCut;\nuniform float armoryTapShift;\nfloat armoryOctCut = 0.0;\n${HULL_FBM}`)
    .replace(HULL_OCTAVE, 'if (float(i) >= max(uOctaves - armoryOctCut, 1.0)) break;')
    .replace(HULL_SHADOW, `float shadowDensity(vec3 lp, vec3 wp) {
    float shape, detail, event;
    // (lighter.ts: the self-shadow, a soft term, from fewer octaves on a hull that fills the screen)
    armoryOctCut = armoryLight > 0.5 ? armoryShadowCut : 0.0;
    float armoryD = mediumDensity(lp, wp, shape, detail, event);
    armoryOctCut = 0.0;
    return armoryD;
  }`)
    .replace(HULL_TAP, 'float h = uShadowLength * (0.45 + float(s) * 1.1 + (armoryLight > 0.5 ? armoryTapShift : 0.0));');
}

/** What a volume that fills the screen gives up (see `lighterVolume`), on a hull whose bounding sphere covers more than
 *  `share` of the screen: a glowing one, its march's steps times `steps` (never under `least`); any other built with a
 *  self-shadow, the shadow's taps down to `taps` (a lone tap stands `tapShift` shadow lengths further out, midway between
 *  the two it replaces) and their density `shadowCut` octaves fewer (never under one). */
export const VOLUME = { on: true, least: 12, share: .25, steps: .5, taps: 1, tapShift: .55, shadowCut: 3 };
const _sphere = new THREE.Sphere(), _view = new THREE.Vector3();

/** A raymarched volume of a participating medium (a material that marches `uSteps` and integrates a transmittance:
 *  VolumeHull, the volumetric fires, the phoenix's body, the found pack's inferno): before each draw, one that covers more
 *  than VOLUME.share of the screen gives up what VOLUME says - steps, and on a VolumeHull its self-shadow's taps and
 *  octaves. What the ability writes (its steps, its taps) is read again whenever it changes, so all of it lets go as soon
 *  as the volume is small. */
export function lighterVolume(mesh: THREE.Mesh) {
  const material = mesh.material as THREE.ShaderMaterial;
  const uniforms = material?.uniforms, steps = uniforms?.uSteps;
  if (!steps || typeof steps.value !== 'number' || !material.isShaderMaterial || !String(material.fragmentShader ?? '').includes('transmittance')
    || (mesh as { __lighter?: boolean }).__lighter) return;
  (mesh as { __lighter?: boolean }).__lighter = true;
  // (A VolumeHull's own: its taps, and the lighter shadow's two values, which its patched program reads: lighterHull.
  // Glowing: a VolumeHull of flame, or a volume that is no VolumeHull at all (the volumetric fires, the fire sim); every
  // other medium of the kit keeps its steps - spores' and the void's too, which have no self-shadow to lighten.)
  const defines = material.defines as { MEDIUM?: unknown; HULL_SHAPE?: unknown; VOLUME_SHADOW?: unknown } | undefined;
  const hull = defines?.MEDIUM !== undefined && defines?.HULL_SHAPE !== undefined;
  const glowing = !hull || Number(defines?.MEDIUM) === 0;
  const taps = hull && Number(defines?.VOLUME_SHADOW) === 1 && typeof uniforms.uShadowTaps?.value === 'number' ? uniforms.uShadowTaps : undefined;
  const cut = (uniforms.armoryShadowCut ??= { value: 0 }) as { value: number }, shift = (uniforms.armoryTapShift ??= { value: 0 }) as { value: number };
  // What the ability asked for, read again whenever it writes a value other than the one set here last.
  let own = steps.value as number, set = NaN, ownTaps = taps ? taps.value as number : 0, setTaps = NaN;
  const before = mesh.onBeforeRender;
  mesh.onBeforeRender = function (renderer, scene, camera, geometry, mat, group) {
    before.call(this, renderer, scene, camera, geometry, mat, group);
    if (steps.value !== set) own = steps.value;
    if (taps && taps.value !== setTaps) ownTaps = taps.value;
    let next = own, nextTaps = ownTaps, nextCut = 0, nextShift = 0;
    const cam = camera as THREE.PerspectiveCamera;
    if (VOLUME.on && LIGHT.value > .5 && cam.isPerspectiveCamera && (geometry.boundingSphere || (geometry.computeBoundingSphere(), geometry.boundingSphere))) {
      // (The hull is sized by its uSize in the vertex stage, never by the mesh's scale: its unit sphere, sized so.)
      const size = uniforms.uSize?.value as THREE.Vector3 | undefined;
      _sphere.copy(geometry.boundingSphere!);
      if (size?.isVector3) { _sphere.center.multiply(size); _sphere.radius *= Math.max(size.x, size.y, size.z); }
      _sphere.applyMatrix4(mesh.matrixWorld);
      _view.copy(_sphere.center).applyMatrix4(cam.matrixWorldInverse);
      const depth = -_view.z, half = Math.tan(THREE.MathUtils.degToRad(cam.fov) / 2);
      // The share of the screen the hull's bounding sphere covers (all of it with the lens inside the sphere).
      const share = depth <= _sphere.radius ? 1 : Math.min(1, Math.PI * (_sphere.radius / (depth * half)) ** 2 / (4 * Math.max(cam.aspect, 1e-3)));
      if (share > VOLUME.share) {
        if (glowing) { if (own > VOLUME.least) next = Math.max(VOLUME.least, Math.round(own * VOLUME.steps)); }
        else if (taps) {
          if (ownTaps > VOLUME.taps) { nextTaps = VOLUME.taps; if (ownTaps === 2 && nextTaps === 1) nextShift = VOLUME.tapShift; }
          nextCut = VOLUME.shadowCut;
        }
      }
    }
    steps.value = set = next;
    if (taps) taps.value = setTaps = nextTaps;
    cut.value = nextCut; shift.value = nextShift;
  };
}
