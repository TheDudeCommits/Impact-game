/** The rows above handed to `seed` (clip, its motion table) for the body's clips they name; nothing else is touched. */
export function seedOriginalClocks(fighter: FighterId, clips: readonly THREE.AnimationClip[], seed: (clip: THREE.AnimationClip, table: Float32Array) => void): number {
  const rows = ORIGINALS[fighter] ? CLOCKS[fighter] : undefined;
  if (!rows) return 0;
  let seeded = 0;
  for (const clip of clips) {
    const row = rows[clip.name];
    if (row && Math.abs(clip.duration - row.span) < .03) { seed(clip, Float32Array.from(row.table)); seeded++; }
  }
  return seeded;
}
